const dictionaries: Record<string, Dictionary> = { en, ka, ru };

export type MessageParams = Record<string, string | number>;

export function translate(
  language: string | null | undefined,
  key: MessageKey,
  params?: MessageParams,
): string {
  const code = (language || "en").split("-")[0] ?? "en";
  const message = dictionaries[code]?.[key] ?? en[key] ?? key;
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function localeTag(language: string | null | undefined): string {
  const code = (language || "en").split("-")[0] ?? "en";
  if (code === "ka") return "ka-GE";
  if (code === "ru") return "ru-RU";
  return "en-US";
}
